   public void habilitar(boolean flag){
       edtTitulo.setEnabled(flag);
       edtAutor.setEnabled(flag);
       edtPreco.setEnabled(flag);
       edtPaginas.setEnabled(flag);
       
   }
   
   
   public void limparCampos(){
       edtTitulo.setText("");
       edtAutor.setText("");
       edtPreco.setText("");
       edtPaginas.setText("");
}
   
   
   public void objetoParaCampos(Livro l){
       edtTitulo.setText(l.getTitulo());
       edtAutor.setText(l.getAutor());
       edtPaginas.setText(l.getNumPag()+"");
       edtPreco.setText(l.getPreco()+""); 
   }
   
   public Livro camposParaObjeto(){
       Livro l= new Livro();
       l.setTitulo(edtTitulo.getText());
       l.setAutor(edtAutor.getText());
       
       String precoStr= edtPreco.getText();
       if(!precoStr.isEmpty()){
           double preco=Double.parseDouble(precoStr);
           l.setPreco(preco);
       }
       String paginasStr= edtPaginas.getText();
       if(!paginasStr.isEmpty()){
           Integer numPag=Integer.parseInt(paginasStr);
           l.setNumPag(numPag);
       }
       return l;
   }
