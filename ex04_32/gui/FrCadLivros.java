    private void btnSalvarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnSalvarActionPerformed
        Livro l=this.camposParaObjeto();
        if(editando){
            this.gerente.atualizar(tituloSelecionado, l);
        }else{
           this.gerente.add(l);
        }
            this.habilitar(true);
            this.limparCampos();
            
            String listagem=this.gerente.listar();
            edtListagem.setText(listagem);
            
        
    }//GEN-LAST:event_btnSalvarActionPerformed

    private void btnCancelarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnCancelarActionPerformed
        this.habilitar(true);
        this.limparCampos();
        this.editando=false;
    }//GEN-LAST:event_btnCancelarActionPerformed

    private void btnExcluirActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnExcluirActionPerformed
        this.tituloSelecionado=JOptionPane.showInputDialog("Digite titulo para remover");
        this.autorSelecionado=JOptionPane.showInputDialog("Digite nome do autor");
        
        Livro l=gerente.pesquisar(tituloSelecionado, autorSelecionado);
        
        if(l != null){
            this.gerente.remover(tituloSelecionado, autorSelecionado);
            JOptionPane.showMessageDialog(this, "Livro Removido");
            this.habilitar(false);
            this.limparCampos();
            
            String listagem=this.gerente.listar();
            edtListagem.setText(listagem);
            
        }else{
            JOptionPane.showMessageDialog(this, "Livro nao Encontrado");
       }
        
    }//GEN-LAST:event_btnExcluirActionPerformed

    private void btnEditarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnEditarActionPerformed
        this.tituloSelecionado=JOptionPane.showInputDialog("Titulo do livro que deseja editar");
        this.autorSelecionado=JOptionPane.showInputDialog("Autor ");
        Livro l=this.gerente.pesquisar(tituloSelecionado, autorSelecionado);
        
        if(l!= null){
            this.objetoParaCampos(l);
            this.editando=true;
            this.habilitar(true);
        }else{
          JOptionPane.showMessageDialog(this,"Livro e autor nao encontrado");
     
        }
    }//GEN-LAST:event_btnEditarActionPerformed

